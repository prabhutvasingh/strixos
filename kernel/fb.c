void fb_clear(uint32_t c){
    if(!fb_graphics){ vga_clear(); fb_cx=0; fb_cy=0; return; }
    for(int y=0;y<fb_height;y++) for(int x=0;x<fb_width;x++) fb_put32(x,y,c);
    fb_cx=0; fb_cy=0;
}
void fb_put_pixel(int x,int y,uint32_t c){ if(!fb_graphics) return; if(x<0||x>=fb_width||y<0||y>=fb_height) return; fb_put32(x,y,c); }
void fb_fill_rect(int x,int y,int w,int h,uint32_t c){
    if(!fb_graphics) return;
    for(int j=y;j<y+h && j<fb_height;j++) for(int i=x;i<x+w && i<fb_width;i++) fb_put32(i,j,c);
}
