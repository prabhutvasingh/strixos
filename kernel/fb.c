static inline void fb_put32(int x,int y,uint32_t c){ if(x<0||x>=fb_width||y<0||y>=fb_height) return; if(fb_bpp==32) fb_base[y*fb_pitch+x]=c; else if(fb_bpp==24){ uint8_t* p=fb_base8+y*fb_pitch_bytes+x*3; p[0]=c&0xFF; p[1]=(c>>8)&0xFF; p[2]=(c>>16)&0xFF; } else if(fb_bpp==16){ uint16_t* p16=(uint16_t*)fb_base8; p16[y*fb_pitch+x]= (uint16_t)(((c>>8)&0xF800)|((c>>5)&0x07E0)|((c>>3)&0x001F)); } else fb_base[y*fb_pitch+x]=c; }

uint32_t rgb(uint8_t r,uint8_t g,uint8_t b){ return ((uint32_t)r<<16)|((uint32_t)g<<8)|b; }

// 8-bit / 256 color palette for TTY display (xterm)
static const uint32_t pal16[16]={
    0x000000,0x800000,0x008000,0x808000,0x000080,0x800080,0x008080,0xc0c0c0,
    0x808080,0xff0000,0x00ff00,0xffff00,0x0000ff,0xff00ff,0x00ffff,0xffffff
};
static uint32_t pal256(uint8_t idx){
    if(idx<16) return pal16[idx];
    if(idx<232){
        idx-=16; int r=idx/36, g=(idx/6)%6, b=idx%6;
        uint8_t rr=r?55+r*40:0, gg=g?55+g*40:0, bb=b?55+b*40:0;
        return rgb(rr,gg,bb);
    } else {
        uint8_t v=8+(idx-232)*10;
        return rgb(v,v,v);
    }
}

