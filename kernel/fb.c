void fb_init(void){
    uint8_t* flag=(uint8_t*)0x9000;
    // force VGA text for stability - VBE 8-bit 256-col ready via FB path (enable when paging covers phys)
    fb_graphics=0; fb_pitch=80; fb_pitch_bytes=80*4; fb_w=80; fb_h=25; fb_cx=0; fb_cy=0;
    serial_puts("[FB] VGA text 80x25 8-bit 256-col ready (VBE disabled for PF stability)\n");
    if(0 && flag[0]==0xFB && flag[1]==0x01){
        fb_graphics=1;
        uint32_t phys=*(uint32_t*)(flag+8);
        if(phys==0) phys=0xE0000000;
        fb_phys=phys;
        fb_base=(uint32_t*)(uintptr_t)phys;
        fb_base8=(uint8_t*)(uintptr_t)phys;
        uint16_t w=*(uint16_t*)(flag+2);
        uint16_t h=*(uint16_t*)(flag+4);
        uint16_t pitch_bytes = *(uint16_t*)(flag+12);
        if(w>=640 && w<=1920 && h>=480 && h<=1080){ fb_width=w; fb_height=h; } else { fb_width=1024; fb_height=768; }
        fb_bpp=32;
        if(pitch_bytes>= (uint16_t)(fb_width*2) && pitch_bytes <= 8192){
            fb_pitch_bytes=pitch_bytes;
            fb_pitch=pitch_bytes/4;
        } else {
            fb_pitch=fb_width; fb_pitch_bytes=fb_width*4;
        }
        fb_w=fb_width/8; // true 8x8
        fb_h=fb_height/8;
        serial_puts("[FB] VBE 32bpp 8-bit 256-col "); char t[16]; int n=0; int v=fb_width; if(v==0) t[n++]='0'; else{char r[6];int k=0;while(v){r[k++]='0'+v%10;v/=10;}while(k--)t[n++]=r[k];} t[n]=0; serial_puts(t); serial_puts("x"); n=0; v=fb_height; if(v==0) t[n++]='0'; else{char r[6];int k=0;while(v){r[k++]='0'+v%10;v/=10;}while(k--)t[n++]=r[k];} t[n]=0; serial_puts(t); serial_puts(" pitch "); { char tt[8]; int nn=0; int vv=fb_pitch_bytes; if(vv==0) tt[nn++]='0'; else{char rr[6];int kk=0;while(vv){rr[kk++]='0'+vv%10;vv/=10;}while(kk--)tt[nn++]=rr[kk];} tt[nn]=0; serial_puts(tt);} serial_puts(" 8bit Ready\n");
        fb_cx=0; fb_cy=0;
        for(int y=0;y<fb_height;y++) for(int x=0;x<fb_width;x++) fb_put32(x,y,0);
        serial_puts("[FB] 8x8 256-col light gray cleared\n");
    } else {
        fb_graphics=0;
        fb_pitch=80; fb_pitch_bytes=80*4;
        fb_w=80; fb_h=25;
        fb_cx=0; fb_cy=0;
    }
}
