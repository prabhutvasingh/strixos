static void fb_draw_char(int x,int y,char ch,uint32_t fg,uint32_t bg){
    if(!fb_graphics) return;
    uint8_t c=(uint8_t)ch; if(c>=128) c='?';
    for(int row=0;row<8;row++){
        uint8_t bits=font8x8_basic[c][row];
        for(int col=0;col<8;col++){
            int px=x*8+col, py=y*8+row;
            if(px>=fb_width||py>=fb_height) continue;
            int bit=(bits>>(7-col))&1; // true 8x8 not stretched
            fb_put32(px,py,bit?fg:bg);
        }
    }
}
static void fb_scroll(void){
    if(!fb_graphics) return;
    if(fb_bpp==32){
        // pitch-aware scroll: move (fb_h-1)*8 scanlines up by 8 lines
        size_t copy_pixels=(size_t)(fb_h-1)*8*fb_pitch;
        // copy using 64-bit where possible but handle pitch correctly
        // Use memmove line by line to respect pitch
        for(int y=0;y<(fb_h-1)*8;y++){
            uint32_t *dst=fb_base+y*fb_pitch;
            uint32_t *src=fb_base+(y+8)*fb_pitch;
            for(int x=0;x<fb_width;x++) dst[x]=src[x];
            for(int x=fb_width;x<fb_pitch;x++) dst[x]=fb_bg;
        }
        // clear last 8 lines
        for(int y=(fb_h-1)*8;y<fb_height;y++){
            uint32_t *row=fb_base+y*fb_pitch;
            for(int x=0;x<fb_width;x++) row[x]=fb_bg;
            for(int x=fb_width;x<fb_pitch;x++) row[x]=fb_bg;
        }
        // also handle generic non-32 via fb_put32 fallback already covered
        (void)copy_pixels;
    } else {
        // generic fallback for 24/16 bpp using fb_put32 stride
        for(int y=0;y<(fb_h-1)*8;y++){
            for(int x=0;x<fb_width;x++){
                // read from src via manual 24 handling? Use fb_put32 to copy?
                // For simplicity copy via temporary buffer: read pixel via direct mem
                uint32_t col=0;
                if(fb_bpp==24){
                    uint8_t* s=fb_base8+(y+8)*fb_pitch_bytes+x*3;
                    col = (uint32_t)s[0]|((uint32_t)s[1]<<8)|((uint32_t)s[2]<<16);
                } else if(fb_bpp==32){
                    col=fb_base[(y+8)*fb_pitch+x];
                }
                fb_put32(x,y,col);
            }
        }
        for(int y=(fb_h-1)*8;y<fb_height;y++) for(int x=0;x<fb_width;x++) fb_put32(x,y,fb_bg);
    }
}
void fb_putchar(char c){
    if(!fb_graphics){ vga_putchar(c); return; }
    static int in_esc=0; static char esc_buf[32]; static int esc_len=0;
    if(in_esc){
        if(esc_len<31) esc_buf[esc_len++]=c;
        if((c>='A'&&c<='Z')||(c>='a'&&c<='z')||c=='~'){
            esc_buf[esc_len]=0;
            if(esc_len>=1 && esc_buf[0]=='['){
                if(c=='K'){ for(int i=fb_cx;i<fb_w;i++) fb_draw_char(i,fb_cy,' ',fb_fg,fb_bg); }
                else if(c=='J'){ fb_clear(fb_bg); }
                else if(c=='H'){ fb_cx=0; fb_cy=0; }
                else if(c=='D'){ if(fb_cx>0) fb_cx--; }
                else if(c=='C'){ if(fb_cx<fb_w-1) fb_cx++; }
                else if(c=='m'){
                    // parse ANSI SGR for 8-bit/24-bit/16 colors
                    int params[16]; int pcnt=0; int cur=0; int has=0;
                    for(int i=1;i<esc_len;i++){
                        char ch=esc_buf[i];
                        if(ch>='0'&&ch<='9'){ cur=cur*10+(ch-'0'); has=1; }
                        else if(ch==';'){ if(pcnt<16){ params[pcnt++]=has?cur:0; } cur=0; has=0; }
                        else if(ch=='m'){ if(pcnt<16){ params[pcnt++]=has?cur:0; } break; }
                    }
                    if(pcnt==0){ params[pcnt++]=0; }
                    int bright=0; int i=0;
                    while(i<pcnt){
                        int v=params[i];
                        if(v==0){ fb_fg=0xBBBBBB; fb_bg=0x000000; bright=0; i++; }
                        else if(v==1){ bright=1; i++; }
                        else if(v==22){ bright=0; i++; }
                        else if(v>=30&&v<=37){ int idx=v-30 + (bright?8:0); fb_fg=pal16[idx]; i++; }
                        else if(v>=40&&v<=47){ int idx=v-40 + (bright?8:0); fb_bg=pal16[idx]; i++; }
                        else if(v>=90&&v<=97){ fb_fg=pal16[(v-90)+8]; i++; }
                        else if(v>=100&&v<=107){ fb_bg=pal16[(v-100)+8]; i++; }
                        else if(v==38||v==48){
                            int is_bg=(v==48);
                            if(i+1<pcnt && params[i+1]==5 && i+2<pcnt){
                                int idx=params[i+2]&0xFF;
                                uint32_t col=pal256((uint8_t)idx);
                                if(is_bg) fb_bg=col; else fb_fg=col;
                                i+=3;
                            } else if(i+1<pcnt && params[i+1]==2 && i+4<pcnt){
                                uint8_t r=params[i+2]&0xFF, g=params[i+3]&0xFF, b=params[i+4]&0xFF;
                                uint32_t col=rgb(r,g,b);
                                if(is_bg) fb_bg=col; else fb_fg=col;
                                i+=5;
                            } else i++;
                        } else i++;
                    }
                }
            }
            in_esc=0; esc_len=0;
        }
        return;
    }
    if(c=='\x1b'){ in_esc=1; esc_len=0; return; }
    if(c==7) return;
    if(c=='\n'){
        fb_cx=0; fb_cy++;
        if(fb_cy>=fb_h){
            fb_scroll();
            fb_cy=fb_h-1;
        }
        return;
    }
    if(c=='\r'){ fb_cx=0; return; }
    if(c=='\b'){ if(fb_cx>0){ fb_cx--; fb_draw_char(fb_cx,fb_cy,' ',fb_fg,fb_bg); } return; }
    if(c=='\t'){
        fb_cx=(fb_cx+8)&~7;
        if(fb_cx>=fb_w){ fb_cx=0; fb_cy++; if(fb_cy>=fb_h){ fb_scroll(); fb_cy=fb_h-1; } }
        return;
    }
    fb_draw_char(fb_cx,fb_cy,c,fb_fg,fb_bg);
    fb_cx++;
    if(fb_cx>=fb_w){
        fb_cx=0; fb_cy++;
        if(fb_cy>=fb_h){
            fb_scroll();
            fb_cy=fb_h-1;
        }
    }
}
